"""Explicit home-only outbound projections; legacy full exports remain the default.

Mixed/audit/private-preference tables are deliberately omitted rather than guessed
from actor names or free text. This readable export is not a restorable database.
"""
import csv
import io
import json
from pathlib import Path
import re

MARKER = ".decklab-export-scope.json"
MARKER_TEXT = '{"version":1,"scope":"home"}\n'
MAX_SCOPE_COMMITS = 256
MAX_HISTORY_COMMITS = 100_000
HOME_ROWS = frozenset({"public.product", "public.product_item", "public.product_status", "public.purchase_order",
                       "public.order_component", "public.order_card_item", "public.order_token_item", "public.watchlist_item",
                       "public.packing_tick", "public.commander_night"})
SPACE_ROWS = frozenset({"public.profile", "public.collection_card", "public.collection_import", "public.token_card",
                        "public.dice_counter", "public.card_loan", "public.deck", "public.space_storage"})
EXCLUDED = frozenset({"public.profile_email", "audit.change_set", "public.wishlist_entry", "public.profile_setting",
                      "public.simulation_mode",
                      "public.visibility", "public.space_departure", "public.field_policy", "public.shop_postage",
                      "public.pricing_setting", "public.inventory_revision", "public.decks_revision"})
FILTERS = {**dict.fromkeys(HOME_ROWS, ("", ())),
           **dict.fromkeys(SPACE_ROWS, ("space_id = %s", ("home",))),
           "public.space": ("id = %s", ("home",)),
           "public.deck_revision": ("split_part(deck_id, '/', 1) in ('casual', 'commander')", ()),
           "public.deck_alias": ("split_part(alias_id, '/', 1) in ('casual', 'commander') "
                                 "and split_part(deck_id, '/', 1) in ('casual', 'commander')", ()),
           "public.play_record": ("(not content ? 'space' or content->>'space' = 'home') and not exists "
                                  "(select 1 from unnest(deck_ids) d where split_part(d, '/', 1) not in "
                                  "('casual', 'commander', 'product', 'pairing'))", ()),
           "public.accessory": ("owner in ('shared', '') or owner in "
                                "(select id from public.profile where space_id = %s)", ("home",))}
README = """# Deck Lab data export

This is an opt-in home-only readable export, not a complete database backup.
Only the home space's collection, tokens, dice/counters, loans, imports, decks,
accessories and household purchase/product tables are included. Profile rows
are limited to home; email addresses and all wishlists are omitted.

Home-only games/plans, Commander-night notes and packing ticks are included.
Mixed play records and audit records, preferences, global revision/settings/visibility rows
and departed-member identities are omitted. Member files and accessory pictures
not referenced by a home accessory are excluded. The encrypted/full pg_dump
backups, not these partial tables, are the disaster-recovery source.

Do not edit these files. A scoped export requires a fresh export repository;
the exporter never rewrites old history or removes an existing remote archive.
The scope marker records this contract for every generated commit.
"""


def setting(settings):
    value = settings.get("export_remote_scope")
    if value is None:
        return None
    if value != "home":
        raise ValueError("database.export_remote_scope must be null or home")
    return value


def included(name):
    if name in FILTERS:
        return True
    if name in EXCLUDED:
        return False
    raise ValueError("A new export table needs an explicit home-scope review")


def home_owners(c):
    return {"shared", "", *(row[0] for row in c.execute("select id from public.profile where space_id = %s", ("home",)))}


def keep_row(name, columns, row):
    """Check actual play participants too; an inconsistent indexed deck_ids array grants no export."""
    if name != "public.play_record":
        return True
    from decklab.lib import spaces, state
    from decklab.lib.state.play import record_deck_ids
    try:
        values = dict(zip(columns, row))
        kind, content = values["kind"], json.loads(values["content"])
        if kind not in ("games", "sideboards") or not isinstance(content, dict):
            raise ValueError
        ids = record_deck_ids(kind, content)
        return content.get("space", "home") == "home" and bool(ids) \
            and all(spaces.split_deck_id(deck_id)[0] == spaces.HOME for deck_id in ids)
    except (KeyError, TypeError, ValueError, state.Invalid):
        raise ValueError("The home-only export cannot classify a play record") from None


def files_home(files, owners):
    """Filter generated bytes before any file is written; shared pictures follow retained kit rows."""
    if files is None:
        return None
    out, images = {}, set()
    accessory_path = "magic/accessories.csv"
    for name, data in files.items():
        parts = name.split("/")
        if parts[:1] != ["magic"] or any(part in ("", ".", "..") or any(ord(ch) < 32 or ch in '\\:<>"|?*' for ch in part)
                                          or re.fullmatch(r"(?i)(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\..*)?", part) for part in parts):
            raise ValueError("The scoped export contains an unsafe inventory path")
        if parts[1:2] in (["people"], ["wishlists"]):
            continue
        if parts[1:3] == ["accessories", "images"]:
            continue
        if name == accessory_path:
            try:
                reader = csv.DictReader(io.StringIO(data.decode("utf-8")), strict=True)
                columns = reader.fieldnames
                if not columns or "owner" not in columns or "image" not in columns:
                    raise ValueError("The scoped export cannot classify its accessory rows")
                rows = [row for row in reader if row.get("owner") in owners]
            except (csv.Error, UnicodeError):
                raise ValueError("The scoped export cannot read its accessory rows") from None
            if any(None in row for row in rows):
                raise ValueError("The scoped export cannot read its accessory rows")
            stream = io.StringIO()
            writer = csv.DictWriter(stream, fieldnames=columns, lineterminator="\n")
            writer.writeheader()
            writer.writerows(rows)
            data = stream.getvalue().encode("utf-8")
            images.update(row["image"] for row in rows if row.get("image"))
        out[name] = data
    for name in images:
        if any(ord(ch) < 32 or ch in '/\\:<>"|?*' for ch in name) or name in (".", ".."):
            raise ValueError("The scoped export contains an unsafe accessory picture")
        rel = "magic/accessories/images/" + name
        if rel in files:
            out[rel] = files[rel]
    return dict(sorted(out.items()))


def _home_marker(text):
    try:
        return json.loads(text) == {"version": 1, "scope": "home"}
    except (ValueError, TypeError):
        return False


def check_history(repo, scope, git):
    """Refuse a scope transition before data reads/writes, commits or pushes.

    Roots and every marker-changing commit are checked across all local refs.
    Earlier unscoped/full histories require a new operator-selected repository,
    never an automated history rewrite or a reassuring current-tree cleanup.
    """
    target = Path(repo) / MARKER
    if scope is None:
        if target.exists():
            raise ValueError("This export repository is home-only; choose a separate repository for full exports")
        return
    commits = set()
    for args in (("rev-list", "--max-parents=0", "--all"), ("log", "--all", "--format=%H", "--", MARKER)):
        code, output = git(repo, *args)
        if code != 0:
            raise ValueError("The export scope history cannot be verified")
        commits.update(output.splitlines())
    if len(commits) > MAX_SCOPE_COMMITS or any(not re.fullmatch(r"[0-9a-f]{40,64}", commit) for commit in commits):
        raise ValueError("The export scope history cannot be verified")
    for commit in commits:
        code, text = git(repo, "show", f"{commit}:{MARKER}")
        if code != 0 or not _home_marker(text):
            raise ValueError("Home-only exports require a fresh export repository; old history is not sanitized")
    if commits and (not target.is_file() or not _home_marker(target.read_text(encoding="utf-8"))):
        raise ValueError("The home-only export scope marker is missing or changed")


def check_tree(repo):
    """Only exporter-managed paths may enter a scoped commit; never follow a linked source."""
    roots = {"tables", "wishlists", "magic", "README.md", ".gitattributes", MARKER}
    for entry in Path(repo).iterdir():
        if entry.name == ".git":
            continue
        if entry.is_symlink() or entry.name not in roots:
            raise ValueError("A home-only export repository contains an unmanaged or linked path")
        for path in (entry, *entry.rglob("*")) if entry.is_dir() else (entry,):
            if path.is_symlink():
                raise ValueError("A home-only export repository contains a linked path")
            if entry.name in ("tables", "wishlists") and path != entry:
                suffix = ".csv" if entry.name == "tables" else ".json"
                if path.parent != entry or not path.is_file() or path.suffix != suffix:
                    raise ValueError("A home-only export repository contains an unmanaged table or wishlist path")


def check_remote(repo, git):
    """An existing remote may expose other branches/history: accept only empty or locally verified refs."""
    code, local = git(repo, "rev-list", "--all", f"--max-count={MAX_HISTORY_COMMITS + 1}")
    commits = set(local.splitlines())
    if code != 0 or len(commits) > MAX_HISTORY_COMMITS:
        raise ValueError("The home-only export's remote history cannot be verified")
    code, remote = git(repo, "ls-remote", "origin")
    if code != 0:
        raise ValueError("The home-only export's destination history cannot be verified")
    for line in remote.splitlines():
        pieces = line.split()
        if len(pieces) != 2 or not re.fullmatch(r"[0-9a-f]{40,64}", pieces[0]) or pieces[0] not in commits:
            raise ValueError("Home-only exports need an empty remote or history already verified locally; no old remote was changed")
