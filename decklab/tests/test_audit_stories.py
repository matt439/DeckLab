"""The story-count audit against small design files in a temporary folder, and the repo's own."""

import contextlib
import io
import tempfile
import unittest
from pathlib import Path

from scripts import audit_stories


STORIES = """# Stories

## How to read this file

**E1-S01** in prose isn't a header, and neither is `**E9-S99** · x`.

## Summary

| Epic | Stories | Built | Partial | Missing | Not wanted |
|---|---:|---:|---:|---:|---:|
| [E1: Find, plan and choose decks](#e1-find-plan-and-choose-decks) | 3 | 1 | 1 | 1 | 0 |
| [E2: Sleeves & boxes](#e2-sleeves--boxes) | 2 | 1 | 0 | 0 | 1 |
| **Total** | **5** | **2** | **1** | **1** | **1** |

Generated by the script.

---

## E1: Find, plan and choose decks

**E1-S01** · User1 · must · M · built

As User1, I want a library.

**E1-S02** · Matt · should · S · partial

As Matt, I want it on a phone.

Awaiting: iphone, ipad

---

**E1-S05** · Matt · could · L · missing

## E2: Sleeves & boxes

**E2-S01** · Claude Code · must · S · built

**E2-S02** · Matt · wont · S · not_wanted
"""

README = """# Design

## The epics

| Epic | Title | What it covers | Built | Partial | Missing | Not wanted |
|---|---|---|---|---|---|---|
| E1 | Find, plan and choose decks | The library, `a\\|b` commands | 1 | 1 | 1 | 0 |
| E2 | Sleeves & boxes | Kit | 1 | 0 | 0 | 1 |

## Headline counts

- **10 personas:** two primary.
- **2 epics, 5 stories:** 2 built, 1 partial, 1 missing and 1 not wanted (kept words).
- **Must and should stories:** by hand.
"""

TODO = """# TODO

| id | status | pri | size | item |
|---|---|---|---|---|
| `E1-S02` | DECISION | should | S | Check it on the phones. |
| `E1-S05` | OPEN | could | L | Build it. |
"""


class AuditStoriesTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        (self.root / "decklab" / "design").mkdir(parents=True)
        self.put(audit_stories.STORIES, STORIES)
        self.put(audit_stories.README, README)
        self.put(audit_stories.TODO, TODO)

    def put(self, name, text, newline="\n"):
        with open(self.root / name, "w", encoding="utf-8", newline="") as handle:
            handle.write(text.replace("\n", newline))

    def raw(self, name):
        with open(self.root / name, encoding="utf-8", newline="") as handle:
            return handle.read()

    def run_script(self, *argv):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = audit_stories.main(list(argv), root=self.root)
        return code, out.getvalue()

    def flip(self, old, new, name=audit_stories.STORIES):
        text = self.raw(name)
        self.assertIn(old, text)
        self.put(name, text.replace(old, new))

    def test_counts_come_from_the_headers_per_epic(self):
        epics, stories, problems = audit_stories.parse_stories(STORIES)
        self.assertEqual(problems, [])
        self.assertEqual(epics, [("E1", "Find, plan and choose decks"), ("E2", "Sleeves & boxes")])
        self.assertEqual([story.id for story in stories], ["E1-S01", "E1-S02", "E1-S05", "E2-S01", "E2-S02"])
        counts = audit_stories.count(epics, stories)
        self.assertEqual(counts["E1"], {"built": 1, "partial": 1, "missing": 1, "not_wanted": 0})
        self.assertEqual(counts["E2"], {"built": 1, "partial": 0, "missing": 0, "not_wanted": 1})
        self.assertEqual(stories[1].awaiting, ["iphone", "ipad"])

    def test_check_passes_when_the_blocks_agree(self):
        code, out = self.run_script("--check")
        self.assertEqual(code, 0, out)
        self.assertIn("2 epics, 5 stories: 2 built, 1 partial, 1 missing, 1 not wanted.", out)

    def test_a_flipped_status_fails_the_check_until_write(self):
        self.flip("**E1-S05** · Matt · could · L · missing", "**E1-S05** · Matt · could · L · built")
        code, out = self.run_script("--check")
        self.assertEqual(code, 1)
        self.assertIn(audit_stories.STORIES, out)
        self.assertIn(audit_stories.README, out)
        self.assertIn("--write", out)

        code, out = self.run_script("--write")
        self.assertEqual(code, 0, out)
        stories, readme = self.raw(audit_stories.STORIES), self.raw(audit_stories.README)
        self.assertIn("(#e1-find-plan-and-choose-decks) | 3 | 2 | 1 | 0 | 0 |", stories)
        self.assertIn("| **Total** | **5** | **3** | **1** | **0** | **1** |", stories)
        self.assertIn("| E1 | Find, plan and choose decks | The library, `a\\|b` commands | 2 | 1 | 0 | 0 |", readme)
        self.assertIn("- **2 epics, 5 stories:** 3 built, 1 partial, 0 missing and 1 not wanted (kept words).", readme)
        self.assertEqual(self.run_script("--check")[0], 0)

    def test_write_is_idempotent_and_touches_only_the_blocks(self):
        self.flip("**E2-S01** · Claude Code · must · S · built", "**E2-S01** · Claude Code · must · S · partial")
        before = self.raw(audit_stories.STORIES).splitlines()
        self.assertEqual(self.run_script("--write")[0], 0)
        once = (self.raw(audit_stories.STORIES), self.raw(audit_stories.README))
        changed = [
            old for old, new in zip(before, once[0].splitlines()) if old != new
        ]
        self.assertTrue(changed)
        self.assertTrue(all(line.startswith("|") for line in changed), changed)
        code, out = self.run_script("--write")
        self.assertEqual(code, 0)
        self.assertIn("already agree", out)
        self.assertEqual((self.raw(audit_stories.STORIES), self.raw(audit_stories.README)), once)

    def test_write_on_agreeing_files_changes_no_byte_and_keeps_crlf(self):
        self.put(audit_stories.STORIES, STORIES, newline="\r\n")
        self.put(audit_stories.README, README, newline="\r\n")
        before = (self.raw(audit_stories.STORIES), self.raw(audit_stories.README))
        self.assertEqual(self.run_script("--write")[0], 0)
        self.assertEqual((self.raw(audit_stories.STORIES), self.raw(audit_stories.README)), before)
        self.flip("· L · missing", "· L · built")
        self.assertEqual(self.run_script("--write")[0], 0)
        for name in (audit_stories.STORIES, audit_stories.README):
            text = self.raw(name)
            self.assertNotIn("\n", text.replace("\r\n", ""), name)
            self.assertNotIn("\r\r", text, name)

    def test_a_stale_readme_alone_fails_the_check(self):
        self.flip("| Kit | 1 | 0 | 0 | 1 |", "| Kit | 2 | 0 | 0 | 0 |", audit_stories.README)
        code, out = self.run_script("--check")
        self.assertEqual(code, 1)
        self.assertIn(audit_stories.README, out)
        self.flip("5 stories:** 2 built", "4 stories:** 1 built", audit_stories.README)
        self.assertEqual(self.run_script("--write")[0], 0)
        self.assertEqual(self.raw(audit_stories.README), README)

    def test_a_new_story_and_a_renamed_epic_reach_both_tables(self):
        self.flip("## E2: Sleeves & boxes\n", "## E2: Kit\n\n**E2-S03** · Matt · could · XL · missing\n")
        self.assertEqual(self.run_script("--check")[0], 1)
        self.assertEqual(self.run_script("--write")[0], 0)
        self.assertIn("| [E2: Kit](#e2-kit) | 3 | 1 | 0 | 1 | 1 |", self.raw(audit_stories.STORIES))
        self.assertIn("| E2 | Kit | Kit | 1 | 0 | 1 | 1 |", self.raw(audit_stories.README))
        self.assertIn("- **2 epics, 6 stories:**", self.raw(audit_stories.README))

    def test_malformed_headers_are_named_and_nothing_is_written(self):
        cases = {
            "· L · missing": ("· L · mising", "status 'mising'"),
            "· Matt · could · L ·": ("· Matt · maybe · L ·", "priority 'maybe'"),
            "· could · L · missing": ("· could · huge · missing", "size 'huge'"),
            "**E1-S05** · Matt · could · L · missing": ("**E1-S05** · could · L · missing", "story header isn't"),
            "**E1-S05** ·": ("**E1-S01** ·", "used twice"),
            "**E2-S02** ·": ("**E3-S02** ·", "under E2's heading"),
        }
        for old, (new, message) in cases.items():
            with self.subTest(message):
                self.put(audit_stories.STORIES, STORIES)
                self.flip(old, new)
                before = self.raw(audit_stories.STORIES)
                for mode in ("--check", "--write"):
                    code, out = self.run_script(mode)
                    self.assertEqual(code, 1, out)
                    self.assertIn(message, out)
                self.assertEqual(self.raw(audit_stories.STORIES), before)

    def test_blocks_write_cannot_generate_are_refused(self):
        cases = [
            (audit_stories.README, "| E2 | Sleeves & boxes | Kit | 1 | 0 | 0 | 1 |\n", "", "one row for each of E1, E2"),
            (audit_stories.README, "- **2 epics, 5 stories:**", "- **Two epics:**", "exactly one line"),
            (audit_stories.README, "## The epics", "## Epics", "no '## The epics' heading"),
            (audit_stories.STORIES, "## Summary", "## Totals", "no '## Summary' heading"),
            (audit_stories.STORIES, "|---|---:|---:|---:|---:|---:|\n", "\n", "exactly one table"),
        ]
        for name, old, new, message in cases:
            with self.subTest(message):
                self.put(audit_stories.STORIES, STORIES)
                self.put(audit_stories.README, README)
                self.flip(old, new, name)
                before = (self.raw(audit_stories.STORIES), self.raw(audit_stories.README))
                for mode in ("--check", "--write"):
                    code, out = self.run_script(mode)
                    self.assertEqual(code, 1, out)
                    self.assertIn(message, out)
                self.assertEqual((self.raw(audit_stories.STORIES), self.raw(audit_stories.README)), before)

    def test_the_plain_report_lists_must_and_should_by_persona(self):
        code, out = self.run_script()
        self.assertEqual(code, 0)
        self.assertIn("  Matt: 1 partial (E1-S02)", out)
        self.assertIn("  User1: 1 built", out)
        self.assertIn("  Claude Code: 1 built", out)

    def test_sessions_lists_waiting_checks_by_device_against_todo(self):
        self.flip(
            "**E1-S05** · Matt · could · L · missing\n",
            "**E1-S05** · Matt · could · L · partial\n\n**Awaiting:** decision, ipad\n\n"
            "**E1-S06** · Matt · could · S · partial\n\nAwaiting: ipad\n\n"
            "**E1-S07** · Matt · could · S · partial\n",
        )
        self.flip("| `E1-S05` | OPEN |", "| `E1-S07` | DECISION | could | S | Decide. |\n| `E1-S05` | OPEN |", audit_stories.TODO)
        code, out = self.run_script("--sessions")
        self.assertEqual(code, 0, out)
        lines = out.splitlines()
        self.assertEqual(lines[lines.index("ipad (3):") + 1:][:3], [
            "  E1-S02  TODO.md: DECISION", "  E1-S05  TODO.md: OPEN", "  E1-S06  TODO.md: no row",
        ])
        self.assertEqual(lines[lines.index("iphone (1):") + 1], "  E1-S02  TODO.md: DECISION")
        self.assertEqual(lines[lines.index("decision (1):") + 1], "  E1-S05  TODO.md: OPEN")
        self.assertIn("Awaiting a check but without a TODO.md row: E1-S06", lines)
        self.assertIn("Partial stories with a DECISION row in TODO.md but no Awaiting line: E1-S07", lines)

    def test_sessions_without_awaiting_lines_or_todo(self):
        self.flip("Awaiting: iphone, ipad\n", "")
        (self.root / audit_stories.TODO).unlink()
        code, out = self.run_script("--sessions")
        self.assertEqual(code, 0)
        self.assertIn("No partial story has an Awaiting line.", out)

    def test_bad_awaiting_lines_fail_the_check(self):
        cases = [
            ("Awaiting: iphone, ipad", "Awaiting: iphone,, ipad", "comma-separated list"),
            ("Awaiting: iphone, ipad", "Awaiting:", "comma-separated list"),
            ("Awaiting: iphone, ipad", "Awaiting: ipad, ipad", "comma-separated list"),
            ("Awaiting: iphone, ipad", "Awaiting: ipad\n\nAwaiting: iphone", "two Awaiting lines"),
            ("As User1, I want a library.", "Awaiting: iphone", "only a partial story"),
        ]
        for old, new, message in cases:
            with self.subTest(new):
                self.put(audit_stories.STORIES, STORIES)
                self.flip(old, new)
                for mode in ("--check", "--sessions"):
                    code, out = self.run_script(mode)
                    self.assertEqual(code, 1, out)
                    self.assertIn(message, out)

    def test_anchor_matches_githubs_heading_slug(self):
        self.assertEqual(audit_stories.anchor("E1: Find, plan and choose decks"), "e1-find-plan-and-choose-decks")
        self.assertEqual(audit_stories.anchor("E8: Sleeves, boxes and storage"), "e8-sleeves-boxes-and-storage")
        self.assertEqual(audit_stories.anchor("E2: Sleeves & boxes"), "e2-sleeves--boxes")

    def test_the_repos_own_tables_agree_with_its_headers(self):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = audit_stories.main(["--check"])
        self.assertEqual(code, 0, out.getvalue())


if __name__ == "__main__":
    unittest.main()
