"""Offline protocol checks against recorded outputs of the real XMage bridge.

The four request/result pairs were generated by scripts/xmage_qualify.py using
synthetic cards-only lists. They retain the original native responses, including
XMage's nonplayed preflight stubs and its timeout before coverage was available.
No installation descriptor, command, stderr, household deck or local path is kept.
The recorded artifact identity is fixed evidence, not a requirement on this PC's JDK.
"""
from copy import deepcopy
import json
from pathlib import Path
import unittest

from decklab.lib.crosscheck import adapters, model

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "crosscheck"
IDENTITY = "647f120e39799bedf12766d6e0327543ddd5d696601f19d77e618acda184f4af"
PROVENANCE = {
    "source_revision": "79aec614fc29d0c3eebd10fff0d5c1b40852bd52",
    "engine_sha256": "596c4ca03d3be39230714bf28672543d30109c9c8eb8396d6f0ecdec20a67805",
    "bridge_sha256": "6330838c170dc9efbb68aecd25197c920286f4ae9db70fd409e7bd79532357dd",
    "bridge_source_sha256": "8f524860e97a2ad78df2bab190ab038af020507386ac88d4e85123fb89e8c5d0",
    "identity_sha256": IDENTITY,
}
REQUEST_DIGESTS = {
    "casual-sol-ring": "f2ac73874a03b34f7dba450369164d1dc145d50707e1f3504a94bb374db8a744",
    "missing-card": "c311570bd06a83b58ac367a911aeee0b3741d00857033d3e7a75c65fab1e620c",
    "invalid-partners": "5487755ea4e2de79e1e5c5ec487b2418bad796a507e9b182019c2ef1103a919d",
    "timeout": "416ad75593a41e58493e473f3f6ee3a26c81e9338c1c7beefd5df2a6c6bf2d4b",
}


def recorded(name):
    request = json.loads((FIXTURES / f"{name}.request.json").read_text(encoding="utf-8"))
    response = json.loads((FIXTURES / f"{name}.result.json").read_text(encoding="utf-8"))
    return request, response


def validate(request, response):
    return adapters.validate_response(response, "xmage", request, IDENTITY, PROVENANCE)


class RecordedXmageProtocolTests(unittest.TestCase):
    def test_every_recorded_response_binds_its_exact_canonical_request_and_artifacts(self):
        for name, expected in REQUEST_DIGESTS.items():
            with self.subTest(name=name):
                request, response = recorded(name)
                self.assertEqual(model.digest(request), expected)
                self.assertEqual(response["request_sha256"], expected)
                self.assertEqual(response["identity_sha256"], IDENTITY)
                for key, value in PROVENANCE.items():
                    self.assertEqual(response[key], value)
                validate(request, response)

    def test_completed_casual_game_keeps_the_actual_winner_and_requested_starting_seat(self):
        request, response = recorded("casual-sol-ring")
        game, coverage = validate(request, response)
        self.assertEqual(request["format"], "casual")
        self.assertIn({"name": "Sol Ring", "quantity": 4}, request["decks"][0]["main"])
        self.assertEqual(game, {"arm": "baseline", "number": 2, "seed": 1501, "starting_player": 1,
                                "status": "completed", "winner": "opponent", "turns": 13,
                                "reproducible": False})
        self.assertEqual([row["status"] for row in coverage], ["supported", "supported"])
        self.assertEqual([row["cards"] for row in coverage], [60, 60])

    def test_recorded_missing_card_is_preflight_evidence_and_never_a_played_game(self):
        request, response = recorded("missing-card")
        self.assertEqual(response["games"][0]["status"], "unsupported")
        game, coverage = validate(request, response)
        self.assertIsNone(game)
        self.assertEqual(coverage[0]["status"], "unsupported")
        self.assertEqual(coverage[0]["missing"], ["No Such Deck Lab Fixture Card"])
        self.assertEqual(coverage[1]["status"], "supported")

    def test_recorded_invalid_commander_pair_is_not_a_loss_or_a_silent_replacement(self):
        request, response = recorded("invalid-partners")
        self.assertEqual(len(request["decks"][0]["commander"]), 2)
        game, coverage = validate(request, response)
        self.assertIsNone(game)
        self.assertEqual(coverage[0]["status"], "invalid")
        self.assertEqual(coverage[0]["missing"], [])
        self.assertTrue(coverage[0]["errors"])
        self.assertIn("Invalid commander pair", coverage[0]["errors"][0])

    def test_recorded_timeout_before_coverage_remains_an_unsuccessful_game(self):
        request, response = recorded("timeout")
        self.assertEqual(response["coverage"], [])
        game, coverage = validate(request, response)
        self.assertEqual(game["status"], "timeout")
        self.assertIsNone(game["winner"])
        self.assertEqual((game["number"], game["seed"], game["starting_player"]), (2, 1501, 1))
        self.assertFalse(game["reproducible"])
        self.assertEqual(coverage, [])

    def test_an_altered_request_cannot_reuse_the_recorded_response(self):
        for name in REQUEST_DIGESTS:
            with self.subTest(name=name):
                request, response = recorded(name)
                request["decks"][0]["main"][0]["quantity"] += 1
                with self.assertRaises(model.CrosscheckError):
                    validate(request, response)

    def test_another_installation_identity_is_rejected_for_every_recording(self):
        for name in REQUEST_DIGESTS:
            with self.subTest(name=name):
                request, response = recorded(name)
                response["identity_sha256"] = "0" * 64
                with self.assertRaises(model.CrosscheckError):
                    validate(request, response)

    def test_a_changed_engine_or_bridge_cannot_hide_behind_the_original_identity(self):
        request, response = recorded("casual-sol-ring")
        for key in PROVENANCE:
            with self.subTest(key=key):
                changed = deepcopy(response)
                changed[key] = "0" * (40 if key == "source_revision" else 64)
                with self.assertRaises(model.CrosscheckError):
                    validate(request, changed)

    def test_nonplayed_stubs_cannot_smuggle_a_winner_or_game_progress(self):
        for name in ("missing-card", "invalid-partners"):
            request, response = recorded(name)
            for key, value in (("winner", "subject"), ("turns", 1), ("status", "completed"),
                               ("number", 3), ("seed", 1502), ("starting_player", 0)):
                with self.subTest(name=name, key=key):
                    changed = deepcopy(response)
                    changed["games"][0][key] = value
                    with self.assertRaises(model.CrosscheckError):
                        validate(request, changed)

    def test_a_timeout_cannot_become_a_win_or_an_unconfirmed_completed_game(self):
        request, response = recorded("timeout")
        for key, value in (("winner", "subject"), ("status", "completed")):
            with self.subTest(key=key):
                changed = deepcopy(response)
                changed["games"][0][key] = value
                with self.assertRaises(model.CrosscheckError):
                    validate(request, changed)

    def test_completed_game_numbers_seeds_and_starting_seats_are_not_interchangeable(self):
        request, response = recorded("casual-sol-ring")
        for key, value in (("number", 1), ("seed", 1500), ("starting_player", 0)):
            with self.subTest(key=key):
                changed = deepcopy(response)
                changed["games"][0][key] = value
                with self.assertRaises(model.CrosscheckError):
                    validate(request, changed)

    def test_missing_card_names_must_belong_to_the_original_requested_deck(self):
        request, response = recorded("missing-card")
        response["coverage"][0]["missing"] = ["A Card Not In This Request"]
        with self.assertRaises(model.CrosscheckError):
            validate(request, response)

    def test_supported_game_requires_both_distinct_coverage_records(self):
        request, response = recorded("casual-sol-ring")
        for coverage in (response["coverage"][:1], [response["coverage"][0]] * 2):
            with self.subTest(coverage=coverage):
                changed = deepcopy(response)
                changed["coverage"] = coverage
                with self.assertRaises(model.CrosscheckError):
                    validate(request, changed)

    def test_supported_coverage_cannot_drop_or_invent_card_copies(self):
        request, response = recorded("casual-sol-ring")
        for value in (0, 59, 61, True, 60.0):
            with self.subTest(cards=value):
                changed = deepcopy(response)
                changed["coverage"][0]["cards"] = value
                with self.assertRaises(model.CrosscheckError):
                    validate(request, changed)
